CREATE TABLE IF NOT EXISTS subscriber (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL
);

-- Release toggles, read on every request so they can be flipped while the service is running
CREATE TABLE IF NOT EXISTS release_toggle (
    name    VARCHAR(64) PRIMARY KEY,
    enabled BOOLEAN NOT NULL
);

-- The subscriber service starts switched off until someone releases it
INSERT INTO release_toggle (name, enabled)
SELECT 'subscriber-service', FALSE
WHERE NOT EXISTS (SELECT 1 FROM release_toggle WHERE name = 'subscriber-service');
